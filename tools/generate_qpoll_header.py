#!/usr/bin/env python3
"""
Generate EPD Test Image Header from Image using QPoll Lite Engine.
Reference: https://github.com/yhl88890/qpoll-lite
Supports both:
  1. Raw image source (auto-fits, area-averages, and quantizes via QPoll Lite)
  2. Studio Canvas rendered image (WYSIWYG, direct palette mapping without re-dithering)
"""

import sys
import os
from pathlib import Path
from PIL import Image
import numpy as np

# 保证从 tools 目录导入 qpoll_codec
script_dir = Path(__file__).resolve().parent
sys.path.insert(0, str(script_dir))
import qpoll_codec

def write_header_file(packets: list, output_header_path: str, mode_name: str, panel_type: str, top_down: bool, density: float):
    total_bytes = sum(len(pkt) for pkt in packets)
    header_content = []
    header_content.append("// ===========================================================================")
    header_content.append(f"//  Auto-generated by QPoll Lite Codec ({mode_name})")
    header_content.append(f"//  Panel: 552x768 4-Color (A0/A1: {panel_type}, TopDown: {top_down})")
    header_content.append(f"//  Packets: {len(packets)} | Non-white Density: {density:.2f}% | Wire bytes: {total_bytes}")
    header_content.append("// ===========================================================================\n")
    header_content.append("#ifndef EPD_TEST_IMAGE_H")
    header_content.append("#define EPD_TEST_IMAGE_H\n")
    header_content.append("#include <stdint.h>")
    header_content.append("#include <stdbool.h>\n")
    header_content.append(f"#define EPD_TOTAL_PACKETS {len(packets)}\n")
    header_content.append('#include "epd_protocol.h"\n')
    header_content.append(f"static const epd_packet_t g_epd_packets[{len(packets)}] = {{")

    for i, pkt in enumerate(packets):
        last_flag = "true" if pkt[3] == 1 else "false"
        blk = pkt[5]
        sub = pkt[6]
        pkt_len = len(pkt)
        hex_bytes = ", ".join(f"0x{b:02X}" for b in pkt)
        comma = "," if i < len(packets) - 1 else ""
        header_content.append(f"    {{ {blk}, {sub}, {last_flag}, {pkt_len}, {{ {hex_bytes} }} }}{comma}")

    header_content.append("};\n")
    header_content.append("#endif // EPD_TEST_IMAGE_H\n")

    with open(output_header_path, "w", encoding="utf-8") as f:
        f.write("\n".join(header_content))
    print(f"[QPoll Codec] Header written to: {output_header_path} ({len(packets)} packets, {total_bytes} wire bytes)")

def generate_header(image_path: str,
                    output_header_path: str,
                    preview_png_path: str = None,
                    mode: int = qpoll_codec.MODE_TEXTURE,
                    panel_type: str = "A1",
                    top_down: bool = False,
                    cover: bool = True,
                    rotate_deg: int = 180):
    """
    使用 QPoll Lite 引擎将原始图片转换为 ESP32 固件适用的 epd_test_image.h
    """
    img = Image.open(image_path)
    if rotate_deg != 0:
        print(f"[QPoll Codec] Applying rotation: {rotate_deg} degrees")
        img = img.rotate(rotate_deg, expand=True)
    print(f"[QPoll Codec] Source image loaded: {image_path} ({img.size[0]}x{img.size[1]})")

    # 1. 面积平均适配到 552x768
    fitted = qpoll_codec.area_average_fit(img, qpoll_codec.WIDTH, qpoll_codec.HEIGHT, cover=cover)

    # 2. 墨小佳官方四档量化与抖动
    codes = qpoll_codec.quantize_reink(fitted, mode=mode)
    density = qpoll_codec.calculate_non_white_density(codes)
    mode_name = qpoll_codec.MODES[mode] if 0 <= mode < len(qpoll_codec.MODES) else "Unknown"
    print(f"[QPoll Codec] Quantized [{mode_name}] | Non-white density: {density:.2f}%")

    # 3. 硬件扫描方向打包
    packed = qpoll_codec.pack_codes(codes)
    mapped = qpoll_codec.map_panel_type(packed, panel_type)
    final_packed = qpoll_codec.for_scan_top_down(mapped, top_down)

    # 4. LZO1X 压缩与 D3 APDU 分包
    packets = qpoll_codec.build_d3_packets(final_packed)

    # 5. 写入头文件
    write_header_file(packets, output_header_path, mode_name, panel_type, top_down, density)

    # 6. 生成预览图
    if preview_png_path:
        preview_img = qpoll_codec.unpack_preview_rgb(mapped, panel_type)
        preview_img.save(preview_png_path)
        print(f"[QPoll Codec] Preview saved: {preview_png_path}")

def generate_header_from_canvas(canvas_image_path: str,
                                output_header_path: str,
                                preview_png_path: str = None,
                                panel_type: str = "A1",
                                top_down: bool = False,
                                rotate_deg: int = 180,
                                mode_name: str = "Web Studio WYSIWYG"):
    """
    直接从前端 Web Canvas 渲染好的 4 色预览图（552x768）提取像素，
    100% 忠实还原前端调节与抖动效果，不进行二次抖动。
    """
    img = Image.open(canvas_image_path).convert("RGB")
    if img.size != (qpoll_codec.WIDTH, qpoll_codec.HEIGHT):
        img = img.resize((qpoll_codec.WIDTH, qpoll_codec.HEIGHT), Image.Resampling.NEAREST)

    # 硬件物理朝向反转 (A1 屏体在下排线安装必须反转 180 度使人眼正立)
    if rotate_deg != 0:
        img = img.rotate(rotate_deg)

    arr = np.array(img, dtype=np.int32)
    palette = np.array(qpoll_codec.PALETTE_ARGB, dtype=np.int32)
    diffs = [np.sum(np.abs(arr - p), axis=-1) for p in palette]
    codes = np.argmin(np.stack(diffs, axis=-1), axis=-1).astype(np.uint8)

    density = qpoll_codec.calculate_non_white_density(codes)
    print(f"[QPoll Codec Canvas] Non-white density: {density:.2f}%")

    packed = qpoll_codec.pack_codes(codes)
    mapped = qpoll_codec.map_panel_type(packed, panel_type)
    final_packed = qpoll_codec.for_scan_top_down(mapped, top_down)

    packets = qpoll_codec.build_d3_packets(final_packed)
    write_header_file(packets, output_header_path, mode_name, panel_type, top_down, density)

    if preview_png_path:
        preview_img = qpoll_codec.unpack_preview_rgb(mapped, panel_type)
        preview_img.save(preview_png_path)
        print(f"[QPoll Codec Canvas] Preview saved: {preview_png_path}")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python generate_qpoll_header.py <input_image> [output_header.h] [preview.png]")
        sys.exit(0)
    src = sys.argv[1]
    out_h = sys.argv[2] if len(sys.argv) > 2 else str(Path(__file__).resolve().parent.parent / "firmware" / "main" / "epd_test_image.h")
    prev = sys.argv[3] if len(sys.argv) > 3 else None
    generate_header(src, out_h, prev, mode=qpoll_codec.MODE_GOLD, panel_type="A1", top_down=False, cover=True, rotate_deg=180)
